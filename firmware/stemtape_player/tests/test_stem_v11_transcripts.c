/*
 * test_stem_v11_transcripts.c — Stem Tape v1.1: real wire-transcript replay.
 *
 * Replays the REAL, byte-for-byte tx/rx wire recordings in
 * handoff/v1.1/transcripts/ (each a .json file, converted to a binary sidecar by
 * gen_transcript_bin.py, which verifies each transcript's SHA-256 against
 * handoff/v1.1/SHA256SUMS.txt BEFORE this binary ever runs -- a corrupted
 * or substituted transcript never reaches replay) against the SAME real
 * production functions main.c's 'Q'/'R'/'W'/'F' handlers call:
 * st_ab_session_open_replace()/open_init()/check_write()/
 * verify_song_before_commit()/mark_song_verified() (st_ab_session.c),
 * st_stix_read_library()/select_active()/validate() (st_stix.c),
 * st11_storage_layout_compute()/stcp_build()/region_of_block() (st_stcp.c).
 *
 * This file NEVER reimplements any accept/reject/selection DECISION --
 * every one of those is made by calling the real function. The only code
 * here is: (1) wire FRAMING (splitting a byte stream into P/Q/R/W/F
 * commands per docs/stem-tape-transfer-v1.1.md section 1 -- a fixed,
 * already-specified structure, not a decision), matching exactly what
 * main.c's own xfer_service() dispatch loop does; (2) the same short
 * orchestration sequence main.c's xfer_v11_write()/xfer_v11_refresh_
 * session()/xfer_v11_send_caps() use to call those real functions in the
 * right order (verify-then-check-then-write for a magic-committing
 * write; open-then-build-caps for a capability query) -- mirrored here
 * because ANY caller of this API has to call it in that order, not
 * because this file makes its own decisions; and (3) an in-memory mock
 * eMMC device (the same role test_stem_v11.c's own g_mock_device/
 * mock_read_block serve, persisted here across an entire recorded
 * session instead of one test function).
 *
 * For every transcript, verifies: exact transmitted and returned bytes
 * (byte-for-byte against the real recording); which commands are
 * accepted/rejected (the real ack/NAK byte, from the real functions'
 * real decisions); exact block addresses and write order (parsed
 * directly from the real tx frames, in the order they were recorded);
 * flush placement (the real 'F' ack appears exactly where the transcript
 * recorded it); final A/B storage bytes (every R read-back in the
 * transcript is checked against the actual mock-device bytes, and a
 * final post-replay pass independently re-derives and re-verifies both
 * song copies via the real STSC codec + FNV-1a checksums); and the
 * selected generation/song slot/index slot (compared against the
 * transcript's own declared `result`, transcribed verbatim from the real
 * JSON with a citation comment, matching this whole suite's established
 * convention of never fabricating expected values).
 *
 *     cc -std=c11 -Wall -Wextra -I../src \
 *        ../src/st_crc32.c ../src/st_checksum32.c ../src/st_sector_v11.c \
 *        ../src/st_stix.c ../src/st_stcp.c ../src/st_ab_session.c \
 *        test_stem_v11_transcripts.c -o test_stem_v11_transcripts && \
 *        (cd ../../.. && firmware/stemtape_player/tests/test_stem_v11_transcripts \
 *           audit/transcript-replay-results.json)
 *
 * Must be run with the CURRENT WORKING DIRECTORY at the repository root,
 * with the binary sidecars already generated by gen_transcript_bin.py at
 * build-transcripts/<name>.bin (see .github/workflows/firmware.yml's own
 * call site for the exact generation step).
 */

