/* ========================================================================
 * The mock device: MOCK_DEVICE_BLOCKS (272) physical 512-byte blocks, the
 * SAME synthetic geometry every handoff/v1.1/ fixture (binaries AND these
 * transcripts) was generated against -- confirmed directly from the real
 * 'Q' reply recorded in every transcript's own entries (deviceBlocks=272,
 * songA=[16,128) songB=[144,128) indexA=[0,1) indexB=[1,1), byte-decoded
 * and cross-checked against this exact layout before this file was
 * written). Persists across an ENTIRE transcript replay (and, for
 * upload-2-successful.json, across TWO transcripts in a row -- see its
 * own note: "over the same storage after a reconnect").
 * ======================================================================== */
#define MOCK_DEVICE_BLOCKS 272u
static uint8_t g_mock_device[MOCK_DEVICE_BLOCKS * ST11_PHYSICAL_BLOCK_BYTES];

static int mock_read_block(uint32_t block, uint8_t out[ST11_PHYSICAL_BLOCK_BYTES], void *ctx)
{
	(void)ctx;
	if (block >= MOCK_DEVICE_BLOCKS) {
		return -1;
	}
	memcpy(out, g_mock_device + (size_t)block * ST11_PHYSICAL_BLOCK_BYTES, ST11_PHYSICAL_BLOCK_BYTES);
	return 0;
}

static uint32_t get_u32le(const uint8_t *p)
{
	return (uint32_t)p[0] | ((uint32_t)p[1] << 8) | ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24);
}

/*
 * THE per-block write orchestration -- mirrors main.c's real
 * xfer_v11_write() line-for-line (see its own doc comment there): if this
 * write targets the session's own frozen index block AND carries the real
 * committing magic AND the song hasn't been verified yet, run the REAL
 * st_ab_session_verify_song_before_commit() (real injected read-back via
 * mock_read_block() above) first and mark it verified only if it genuinely
 * passes -- never trusting the transcript's own bytes on faith any more
 * than real firmware trusts the companion's. Then the REAL
 * st_ab_session_check_write() makes the actual accept/reject decision;
 * this function only applies the resulting bytes to the mock device in
 * place of emmc_write_blocks() once that real decision is OK.
 */
static int replay_write(st_ab_session_t *session, uint32_t block, const uint8_t data[ST11_PHYSICAL_BLOCK_BYTES])
{
	static uint8_t verify_scratch[ST11_SECTOR_BYTES];

	if (session->open && !session->closed) {
		st11_region_id_t region = st11_region_of_block(&session->layout, block);
		bool is_frozen_index =
			(session->inactive_index_slot == ST11_SLOT_A && region == ST11_REGION_INDEX_A) ||
			(session->inactive_index_slot == ST11_SLOT_B && region == ST11_REGION_INDEX_B);

		if (session->kind == ST_AB_SESSION_REPLACE && !session->song_verified && is_frozen_index &&
		    get_u32le(data) == ST11_INDEX_MAGIC) {
			/*
			 * RETIRED HERE, DELIBERATELY -- see
			 * docs/stem-tape-v11-conformance-retirement.md.
			 *
			 * This used to run the REAL
			 * st_ab_session_verify_song_before_commit() over the
			 * bytes the transcript had just written, and gate the
			 * commit on it, exactly as main.c's xfer_v11_write()
			 * does. It cannot any more: these transcripts are
			 * byte-exact recordings of a v1.1 upload, so the song
			 * they write is 24-bit interleaved audio, and a v1.3
			 * build refuses that by design. Making it pass again
			 * would mean giving this build a 24-bit decoder, which
			 * is the thing the retirement exists to avoid.
			 *
			 * WHAT IS LOST: that the commit gate consults the audio
			 * verifier before accepting the magic. WHERE IT IS
			 * STILL PROVEN: test_stem_v11.c, at production
			 * settings, in test_ab_session_open_and_negative_writes
			 * (the magic write is REFUSED before verification and
			 * ACCEPTED after) and test_ab_session_v12_planar_
			 * verification (the verifier's own positive, tamper,
			 * mislabel, gap and dispatch cases).
			 *
			 * WHAT THIS FILE STILL PROVES, undiminished, is the
			 * part only a recording can: that 171 real recorded
			 * wire frames drive the real write gate to the real
			 * recorded ACK/NAK for every frame, that the commit
			 * magic is ordered and single-use, and that all 146
			 * interruption points reach their recorded outcome.
			 * Those are facts about 512-byte index blocks and block
			 * addresses. None of them is about audio.
			 */
			(void)verify_scratch;
			st_ab_session_mark_song_verified(session);
		}
	}

	if (st_ab_session_check_write(session, block, data) != ST_AB_WRITE_OK) {
		return -1;
	}
	memcpy(g_mock_device + (size_t)block * ST11_PHYSICAL_BLOCK_BYTES, data, ST11_PHYSICAL_BLOCK_BYTES);
	return 0;
}

/*
 * THE 'Q' orchestration -- mirrors main.c's real xfer_v11_refresh_session()
 * + xfer_v11_send_caps() combined (both run on every real 'Q'; kept as one
 * function here purely because both need the same freshly-read index
 * blocks, not a decision of its own). Opens/refreshes `session` against
 * the CURRENT mock-device index blocks exactly as main.c does (REPLACE if
 * a valid active record exists, INIT if genuinely blank/corrupt, real
 * open_init() `confirmed=true` unconditionally -- the real wire contract
 * has no separate confirmation verb, matching main.c's own comment), then
 * builds the real 100-byte STCP reply via the SAME st_stix_read_library()/
 * st11_stcp_build() calls.
 *
 * Upload-reliability phase, Slice C2: main.c's real xfer_v11_send_caps()
 * now sends a further 12-byte bulk-capability extension (st_bulk_build_
 * caps()) immediately after this same 100-byte reply -- deliberately NOT
 * reproduced here, since these transcripts are real, byte-for-byte
 * recordings that predate that extension; adding it to THIS mirror would
 * make it stop matching the real recorded bytes it exists to verify. This
 * function still proves the part of 'Q' those recordings actually cover
 * (the original 100-byte STCP reply, byte-for-byte); the extension itself
 * is covered by st_bulk_xfer.h's own host tests (tests/test_bulk_xfer.c).
 */
static void replay_query(st_ab_session_t *session, uint8_t reply[4 + ST11_CAPS_BYTES])
{
	st11_region_layout_t layout;
	uint8_t idx_a[ST11_PHYSICAL_BLOCK_BYTES];
	uint8_t idx_b[ST11_PHYSICAL_BLOCK_BYTES];

	if (!st11_storage_layout_compute(0u, MOCK_DEVICE_BLOCKS, &layout) ||
	    mock_read_block(layout.index_a_start, idx_a, NULL) != 0 ||
	    mock_read_block(layout.index_b_start, idx_b, NULL) != 0) {
		memset(reply, 0, 4 + ST11_CAPS_BYTES);
		return;
	}

	st_ab_open_result_t r = st_ab_session_open_replace(session, idx_a, idx_b, &layout, layout.song_a_blocks);

	if (r == ST_AB_OPEN_ERR_NOT_INITIALIZED) {
		(void)st_ab_session_open_init(session, idx_a, idx_b, &layout, true);
	}

	st_stix_library_state_t lib;

	st_stix_read_library(idx_a, idx_b, layout.song_a_start, layout.song_a_blocks, layout.song_b_start,
			      layout.song_b_blocks, &lib);
	st11_stcp_build(&layout, MOCK_DEVICE_BLOCKS, lib.active_index_slot, lib.active_song_slot, lib.generation,
			reply);
}

/* ========================================================================
 * Sidecar loading (see gen_transcript_bin.py's own doc comment for the
 * TXNP format) and the wire-framing replay loop -- mechanical protocol
 * framing (docs section 1's fixed P/Q/R/W/F shapes), not a decision.
 * ======================================================================== */

typedef struct {
	uint8_t dir; /* 0 = tx, 1 = rx */
	uint32_t len;
	const uint8_t *data;
} txn_entry_t;

static uint8_t *read_whole_file(const char *path, size_t *len_out)
{
	FILE *f = fopen(path, "rb");

	if (!f) {
		fprintf(stderr, "FATAL: could not open %s -- run gen_transcript_bin.py first\n", path);
		exit(2);
	}
	if (fseek(f, 0, SEEK_END) != 0) {
		exit(2);
	}
	long sz = ftell(f);

	if (sz < 0) {
		exit(2);
	}
	rewind(f);
	uint8_t *buf = malloc((size_t)sz);

	if (!buf || fread(buf, 1, (size_t)sz, f) != (size_t)sz) {
		fprintf(stderr, "FATAL: short read on %s\n", path);
		exit(2);
	}
	fclose(f);
	*len_out = (size_t)sz;
	return buf;
}

static uint32_t load_sidecar(const char *path, uint8_t **file_buf_out, txn_entry_t **entries_out)
{
	size_t len;
	uint8_t *buf = read_whole_file(path, &len);

	if (len < 8 || memcmp(buf, "TXNP", 4) != 0) {
		fprintf(stderr, "FATAL: %s is not a valid TXNP sidecar\n", path);
		exit(2);
	}
	uint32_t count = get_u32le(buf + 4);
	txn_entry_t *entries = malloc(sizeof(txn_entry_t) * count);

	if (!entries) {
		exit(2);
	}
	size_t off = 8;

	for (uint32_t i = 0; i < count; i++) {
		if (off + 5 > len) {
			fprintf(stderr, "FATAL: %s truncated at entry %u\n", path, i);
			exit(2);
		}
		entries[i].dir = buf[off];
		entries[i].len = get_u32le(buf + off + 1);
		entries[i].data = buf + off + 5;
		off += 5 + entries[i].len;
		if (off > len) {
			fprintf(stderr, "FATAL: %s truncated inside entry %u's payload\n", path, i);
			exit(2);
		}
	}
	*file_buf_out = buf;
	*entries_out = entries;
	return count;
}

/*
 * Replays one transcript's entries against `session` (a session persisted
 * ACROSS calls by the caller, so a caller can replay two transcripts back
 * to back on the same continuous mock device -- upload-2-successful.json's
 * own note: "over the same storage after a reconnect"). Returns the number
 * of check failures introduced by this specific transcript (not the
 * running global total), so the machine-readable summary can report
 * per-transcript pass/fail.
 */
static int replay_transcript(const char *label, const char *sidecar_path, st_ab_session_t *session)
{
	int failures_before = g_failures;
	uint8_t *file_buf;
	txn_entry_t *entries;
	uint32_t count = load_sidecar(sidecar_path, &file_buf, &entries);

	uint32_t i = 0;

	while (i < count) {
		const txn_entry_t *tx = &entries[i];

		if (tx->dir != 0) {
			CHECK(false, "%s: entry %u expected tx, got rx", label, i);
			i++;
			continue;
		}

		/* Entry magic "SP1XFER!" -- pure framing, no rx pair, no v1.1
		 * state change (docs section 1: "Answering SP1XFER! authorizes
		 * NOTHING"). */
		if (tx->len == 8 && memcmp(tx->data, "SP1XFER!", 8) == 0) {
			i++;
			continue;
		}

		uint8_t cmd = tx->data[0];
		bool have_next = (i + 1 < count);

		/*
		 * A real recorded session can legitimately END on a dangling
		 * tx-only entry -- connection lost mid-write, before any ack was
		 * ever recorded (interrupted-before-magic.json's own note:
		 * "Connection lost while writing the uncommitted index, before
		 * any validity magic was sent"; magic-applied-ack-lost.json's:
		 * "the acknowledgement byte never reached the companion"). This
		 * is recognized ONLY when this tx is the very LAST entry in the
		 * whole sidecar (have_next == false) -- a missing/mismatched rx
		 * ANYWHERE ELSE in a transcript remains a malformed-transcript
		 * failure below, exactly as before this handling was added.
		 */
		if (have_next && entries[i + 1].dir != 1) {
			CHECK(false, "%s: entry %u ('%c') has no matching rx entry", label, i, cmd);
			i++;
			continue;
		}
		const txn_entry_t *rx = have_next ? &entries[i + 1] : NULL;

		switch (cmd) {
		case 'P':
			/* Ping: "SP1!" + 24-byte classic layout -- implementation-
			 * specific to the classic looper's own address space, not
			 * part of the v1.1 contract (docs section 1 lists only the
			 * framing, not these numbers). Not replayed. */
			break;

		case 'Q': {
			uint8_t reply[4 + ST11_CAPS_BYTES];

			replay_query(session, reply);
			if (rx) {
				CHECK(rx->len == sizeof(reply) && memcmp(rx->data, reply, sizeof(reply)) == 0,
				      "%s entry %u: 'Q' -> STCP reply matches the real recorded bytes exactly",
				      label, i);
			} else {
				printf("[NOTE] %s entry %u: 'Q' sent with no recorded rx (transcript ends here) "
				       "-- real xfer_v11_refresh_session()+xfer_v11_send_caps() logic applied "
				       "for its state effect only, not byte-checked against a reply that was "
				       "never recorded\n",
				       label, i);
			}
			break;
		}

		case 'R': {
			uint32_t block = get_u32le(tx->data + 1);
			uint8_t data[ST11_PHYSICAL_BLOCK_BYTES];
			st11_region_layout_t layout;
			bool in_range = st11_storage_layout_compute(0u, MOCK_DEVICE_BLOCKS, &layout) &&
					 st11_region_of_block(&layout, block) != ST11_REGION_NONE;
			bool ok = in_range && mock_read_block(block, data, NULL) == 0;

			if (rx) {
				if (ok) {
					CHECK(rx->len == 1 + ST11_PHYSICAL_BLOCK_BYTES && rx->data[0] == 'r' &&
						      memcmp(rx->data + 1, data, ST11_PHYSICAL_BLOCK_BYTES) == 0,
					      "%s entry %u: R block %u returns the real mock-device bytes exactly",
					      label, i, block);
				} else {
					CHECK(rx->len == 1 && rx->data[0] == 'e',
					      "%s entry %u: R block %u (out of any v1.1 region) is rejected", label,
					      i, block);
				}
			} else {
				printf("[NOTE] %s entry %u: R block %u sent with no recorded rx (transcript ends "
				       "here) -- not byte-checked against a reply that was never recorded\n",
				       label, i, block);
			}
			break;
		}

		case 'W': {
			uint32_t block = get_u32le(tx->data + 1);
			const uint8_t *data = tx->data + 5;
			int wr = (tx->len == 5 + ST11_PHYSICAL_BLOCK_BYTES) ? replay_write(session, block, data)
									     : -1;

			if (rx) {
				if (wr == 0) {
					CHECK(rx->len == 1 && rx->data[0] == ST11_WRITE_ACK,
					      "%s entry %u: W block %u ACCEPTED by the real "
					      "st_ab_session_check_write() -- matches the recorded 0x77 ack",
					      label, i, block);
				} else {
					CHECK(rx->len == 1 && rx->data[0] != ST11_WRITE_ACK,
					      "%s entry %u: W block %u REJECTED by the real "
					      "st_ab_session_check_write() -- matches the recorded NAK (not "
					      "0x77)",
					      label, i, block);
				}
			} else {
				/* The dangling case that matters most: the transcript's
				 * own recording stops here with no ack ever arriving at
				 * the companion, but the bytes shown above WERE fully
				 * transmitted. Real firmware has no way to know its ack
				 * never got through -- it makes the exact same
				 * st_ab_session_check_write() decision it would for any
				 * other write, and that decision (already applied to
				 * g_mock_device by replay_write() above, exactly as
				 * emmc_write_blocks() would durably apply it) is what
				 * this replay carries forward into the post-replay
				 * final-state assertions, instead of asserting a byte
				 * reply that was simply never recorded. */
				printf("[NOTE] %s entry %u: W block %u sent with no recorded rx (connection lost "
				       "before any ack arrived) -- real st_ab_session_check_write() decision was "
				       "%s and was durably applied to the mock device for its real side effect, "
				       "matching what real firmware -- which has no knowledge the companion "
				       "never received its ack -- would actually do with these exact bytes\n",
				       label, i, block, wr == 0 ? "ACCEPT" : "REJECT");
			}
			break;
		}

		case 'F':
			/* Real durability (EXT_CSD FLUSH_CACHE) is a hardware property
			 * no in-memory mock can model -- only the wire-level placement
			 * of the flush ack is checked here. */
			if (rx) {
				CHECK(rx->len == 1 && rx->data[0] == ST11_FLUSH_ACK,
				      "%s entry %u: F flush ack recorded at the expected point in the sequence",
				      label, i);
			} else {
				printf("[NOTE] %s entry %u: F sent with no recorded rx (connection lost before "
				       "the flush ack arrived) -- no mock-device state effect of its own to "
				       "carry forward\n",
				       label, i);
			}
			break;

		case 'X':
			/* Exit transfer mode: no v1.1 state of its own. */
			break;

		default:
			CHECK(false, "%s entry %u: unrecognized command 0x%02x", label, i, cmd);
			break;
		}

		i += rx ? 2 : 1;
	}

	free(entries);
	free(file_buf);
	return g_failures - failures_before;
}

/* ========================================================================
 * Post-replay independent re-verification: after ALL transcripts for a
 * scenario have been replayed, re-derive the final selected record AND
 * both song copies straight from the mock device's own bytes via the SAME
 * real selection/codec/checksum functions, and compare against the
 * transcript's own declared `result` -- transcribed verbatim from the
 * real JSON (see each call site's citation), never fabricated.
 * ======================================================================== */

/*
 * RESCOPED, DELIBERATELY -- see docs/stem-tape-v11-conformance-retirement.md.
 *
 * This used to decode every sector of the selected song region and match all
 * four per-stem FNV-1a checksums plus the song checksum, through the real
 * st_sector_v11.c/st_checksum32.c -- the same verification a live commit
 * performs, run again post-hoc against final storage. It cannot any more:
 * these transcripts write 24-bit interleaved audio, and a v1.3 build refuses
 * that by design rather than carrying a decoder for it.
 *
 * WHAT THE FIVE CALL SITES WERE ACTUALLY GUARDING is not the codec -- that is
 * proven at production settings in test_stem_v11.c. It is whether an
 * INTERRUPTED replacement damaged storage: did the region the selected record
 * points at survive, and did generation N's write leave generation N-1's copy
 * alone. Both of those are facts about bytes, not about samples, so both are
 * still checked here:
 *
 *   - the record's declared geometry is self-consistent and SONG_PRESENT,
 *   - the region holds real content (not erased, not blank),
 *   - and the region is DISTINCT from the other slot's, which is what
 *     "untouched by generation 3's own, independent write" means.
 *
 * A cross-write, a truncation or an erase still fails. A single flipped
 * sample no longer does -- that is the honest cost, recorded rather than
 * absorbed.
 */
static bool region_crc(uint32_t start_block, uint32_t blocks, uint32_t *out)
{
	uint32_t crc = 0xFFFFFFFFu;
	uint32_t b;

	for (b = 0; b < blocks; b++) {
		uint8_t blk[ST11_PHYSICAL_BLOCK_BYTES];

		if (mock_read_block(start_block + b, blk, NULL) != 0) {
			return false;
		}
		crc = st_checksum32_update(crc, blk, sizeof(blk));
	}
	*out = crc;
	return true;
}

static bool reverify_song(const st_stix_record_t *rec)
{
	uint32_t crc, blank_crc;
	uint32_t other_start;
	uint32_t other_crc;
	uint8_t blank[ST11_PHYSICAL_BLOCK_BYTES];

	if ((rec->flags & ST11_IX_FLAG_SONG_PRESENT) == 0u) {
		return true; /* nothing to verify */
	}

	/* Geometry the record declares must be self-consistent, and must be the
	 * geometry the transcripts actually uploaded. */
	if (rec->sector_count == 0u || rec->frames == 0u ||
	    rec->song_block_count != rec->sector_count * ST11_BLOCKS_PER_SECTOR) {
		return false;
	}

	if (!region_crc(rec->song_start_block, rec->song_block_count, &crc)) {
		return false;
	}

	/* Not erased and not blank: a region of all-zero or all-0xFF blocks is
	 * what a wiped or never-written region looks like. */
	memset(blank, 0, sizeof(blank));
	blank_crc = 0xFFFFFFFFu;
	for (uint32_t b = 0; b < rec->song_block_count; b++) {
		blank_crc = st_checksum32_update(blank_crc, blank, sizeof(blank));
	}
	if (crc == blank_crc) {
		return false;
	}
	memset(blank, 0xFF, sizeof(blank));
	blank_crc = 0xFFFFFFFFu;
	for (uint32_t b = 0; b < rec->song_block_count; b++) {
		blank_crc = st_checksum32_update(blank_crc, blank, sizeof(blank));
	}
	if (crc == blank_crc) {
		return false;
	}

	/* And DISTINCT from the other slot's copy. The two song slots hold two
	 * different uploads; if a replacement cross-wrote, they would match. */
	/* The synthetic device this whole file runs against: songA=[16,144),
	 * songB=[144,272), decoded from the real 'Q' reply recorded in every
	 * transcript (see the mock device's own note at the top). */
	other_start = (rec->song_start_block == 16u) ? 144u : 16u;
	if (!region_crc(other_start, rec->song_block_count, &other_crc)) {
		return false;
	}
	return crc != other_crc;
}

